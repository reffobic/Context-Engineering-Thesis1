"""
score_answer_quality.py

Runs DeepEval's AnswerRelevancyMetric against answers ALREADY generated by
scripts/live_modes_compare_suite.py — reads the saved JSON, does not
re-run retrieval or generation. Only cost is one judge call per answer.

Why AnswerRelevancyMetric specifically: it only needs (query, answer), not
retrieval_context. The saved compare-suite JSON does NOT store the actual
retrieved/pruned chunk text (only counts like tokens_injected_est), so
FaithfulnessMetric / ContextualRelevancyMetric — which need that context
to judge grounding — can't be computed from what's already saved. Getting
those would mean re-running the pipeline with context capture added, which
this script does not do. Answer relevancy (does the answer address the
question) is what's available tonight; grounding-in-evidence is not.

Usage, from backend/:
    python3 ../scripts/score_answer_quality.py
    python3 ../scripts/score_answer_quality.py --modes GASR GAPA  # faster, fewer judge calls
    python3 ../scripts/score_answer_quality.py --limit 20             # smoke test first
"""

from __future__ import annotations

import argparse
import glob
import json
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent / "backend"
if str(BACKEND) not in sys.path:
    sys.path.insert(0, str(BACKEND))

from context_metrics.run_pipeline_metrics import build_judge_model, metric_result  # noqa: E402


def latest_compare_run() -> Path:
    paths = sorted(glob.glob(
        str(Path(__file__).resolve().parent.parent / "results" / "live_modes_compare" / "modes_compare_run_*.json")
    ))
    if not paths:
        raise SystemExit("No modes_compare_run_*.json found — run live_modes_compare_suite.py first.")
    return Path(paths[-1])


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--modes", nargs="*", default=None, help="Only score these modes, e.g. --modes GASR GAPA")
    parser.add_argument("--limit", type=int, default=None, help="Only score the first N rows (smoke test)")
    args = parser.parse_args()

    from deepeval.metrics import AnswerRelevancyMetric
    from deepeval.test_case import LLMTestCase

    run_path = latest_compare_run()
    data = json.loads(run_path.read_text())
    rows = [r for r in data["results"] if r.get("ok")]
    if args.modes:
        rows = [r for r in rows if r["mode"] in args.modes]
    if args.limit:
        rows = rows[: args.limit]

    print(f"Scoring {len(rows)} answers from {run_path.name}")

    judge = build_judge_model()
    per_mode: dict[str, list[float]] = {}
    detail = []

    for i, row in enumerate(rows, 1):
        query = row["prompt"]
        answer = row["summary"].get("answer_full") or row["summary"].get("answer_preview") or ""
        if not answer.strip():
            print(f"[{i}/{len(rows)}] {row['id']}: SKIPPED (empty answer)")
            continue

        test_case = LLMTestCase(input=query, actual_output=answer)
        metric = AnswerRelevancyMetric(model=judge, async_mode=False)
        try:
            metric.measure(test_case)
        except Exception as exc:  # DeepEval/judge errors — don't let one bad row kill the run
            print(f"[{i}/{len(rows)}] {row['id']}: JUDGE ERROR ({exc})")
            continue

        result = metric_result(metric, stage="answer_relevancy")
        mode = row["mode"]
        per_mode.setdefault(mode, [])
        if result["score"] is not None:
            per_mode[mode].append(result["score"])
        detail.append({
            "id": row["id"], "mode": mode, "compare_group": row.get("compare_group"),
            "score": result["score"], "reason": result["reason"],
        })
        print(f"[{i}/{len(rows)}] {row['id']} ({mode}): score={result['score']}")

    out_dir = Path(__file__).resolve().parent.parent / "results" / "answer_quality"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_path = out_dir / f"{run_path.stem}_answer_relevancy.json"
    out_path.write_text(json.dumps({"source_run": run_path.name, "detail": detail}, indent=2), encoding="utf-8")

    print(f"\n--- Average answer relevancy by mode ---")
    for mode, scores in sorted(per_mode.items()):
        if scores:
            print(f"{mode:<12} n={len(scores):<3} avg={sum(scores)/len(scores):.3f}")
        else:
            print(f"{mode:<12} n=0 (no scored rows)")
    print(f"\nWrote {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())