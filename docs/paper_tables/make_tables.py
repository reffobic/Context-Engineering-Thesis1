def within3(vals: dict, n: int, col: str, ds: str) -> str:
    """Arms whose value lies within 3 tasks of the best arm in column `col` (headline column of the table)."""
    best = max(vals.values())
    close = [a for a, v in vals.items() if v is not None and (best - v) * n <= 3.0000001 and v != best]
    top = [a for a, v in vals.items() if v == best]
    if not close:
        return ""
    return (f"On {DS_LABEL[ds]}, {', '.join(LABEL[a] for a in close)} lie within 3 tasks of "
            f"the best ({', '.join(LABEL[a] for a in top)}) on {col}.")


def note(parts: list[str]) -> str:
    parts = [p for p in parts if p]
    if not parts or PH:                                  # the 3-task note is run-specific: not in the skeleton
        return ""
    return ("\\par\\vspace{2pt}\\scriptsize Note: a difference of 3 tasks or fewer (0.111 of 27 tasks, 0.054 of 56) is a task count, not a result. "
            + " ".join(parts) + "\n")


def table(caption: str, label: str, spec: str, header: str, body: str, notes: str = "") -> str:
    return (f"\\begin{{table}}[!ht]\\scriptsize\\centering\\setlength{{\\tabcolsep}}{{3pt}}\n\\caption{{{caption}}}\\label{{{label}}}\n"
            f"\\resizebox{{\\columnwidth}}{{!}}{{\\begin{{tabular}}{{@{{}}{spec}@{{}}}}\\toprule\n{header}\\midrule\n{body}\\bottomrule\n\\end{{tabular}}}}\n"
            f"{notes}\\end{{table}}\n")


def stacked(blocks: list[list[list[str]]]) -> str:
    """blocks[dataset] = list of row cell lists (first cell = dataset label filled here)."""
    out = []
    for bi, rows in enumerate(blocks):
        for ri, cells in enumerate(rows):
            out.append((DS_LABEL[DATASETS[bi]] if ri == 0 else "") + " & " + " & ".join(cells) + "\\\\")
        out.append("\\midrule" if bi < len(blocks) - 1 else "")
    return "\n".join(x for x in out if x) + "\n"


