# ── skeleton (--placeholder) ─────────────────────────────────────────────────────────────────────────────────
def skeleton(t: str) -> str:
    """Every numeric (and ``-'') cell between the first \\midrule and \\bottomrule becomes --; row/arm/stage labels stay."""
    head, rest = t.split("\\midrule\n", 1)
    body, foot = rest.split("\\bottomrule", 1)
    out = []
    for line in body.split("\n"):
        if line.endswith("\\\\") and "&" in line:
            cells = line[:-2].split("&")
            cells = [c if not re.fullmatch(r"\s*(-?[\d{},.]+|-)\s*", c) else " -- " for c in cells]
            line = "&".join(cells) + "\\\\"
        out.append(line)
    return head + "\\midrule\n" + "\n".join(out) + "\\bottomrule" + foot


def static_table(star: bool, caption: str, label: str, spec: str, header: str, rows: list[str]) -> str:
    env, pos = ("table*", "[t]") if star else ("table", "[!ht]")
    return (f"\\begin{{{env}}}{pos}\\scriptsize\\centering\\setlength{{\\tabcolsep}}{{3pt}}\n\\caption{{{caption}}}\\label{{{label}}}\n"
            + (f"\\begin{{tabular}}{{@{{}}{spec}@{{}}}}\\toprule\n{header}\\midrule\n" if star else
             f"\\resizebox{{\\columnwidth}}{{!}}{{\\begin{{tabular}}{{@{{}}{spec}@{{}}}}\\toprule\n{header}\\midrule\n") + "\n".join(rows) + "\n\\bottomrule\n"
            + ("\\end{tabular}\n" if star else "\\end{tabular}}\n") + f"\\end{{{env}}}\n")


