"""Gold-loss funnel and floor/tier analysis for the Nov 3 jobs (read-only; zero rule: failed tasks score 0).

  python docs/analysis/gate_diagnostics/build_funnel_floor.py

Reads   eval_harness/data/runs/2350c0b/nov3-*/results.jsonl, datasets/*/labels.jsonl, reports/nov3_83/{per_task,answer_scores}.csv
Writes  gold_loss_funnel.md (funnel and floor/tier sections), gold_loss_funnel.csv, floor_tiers.csv next to this file. Nothing else is touched.
"""
from __future__ import annotations

import csv
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "docs" / "analysis"))
import nov3_lib as L                                                       # noqa: E402

DATA = ROOT / "eval_harness" / "data" / "datasets"
CHECKOUTS = ROOT / "eval_harness" / "data" / "cache" / "checkouts"
FUNNEL_ARMS = ["ALWAYS_RAG", "ALWAYS_GRAPH", "GASR", "GAPA"]
STAGES = ["after_retrieval", "after_expansion", "after_pruning", "final_context"]
GATED = ["GASR", "GAPA", "SELF_ROUTE", "PREASSESS"]
RANK = L.ROUTE_RANK


def jl(p):
    return [json.loads(x) for x in open(p, encoding="utf-8") if x.strip()]


res = L.load_results()
pt, ans = L.load_per_task(), L.load_answers()
gold = {ds: {t["instance_id"]: t for t in jl(DATA / ds / "labels.jsonl")} for ds in L.DATASETS}
ids = {ds: sorted(res[(ds, "GAPA")]) for ds in L.DATASETS}
score = {(ds, arm): {r["task_id"]: r for r in L.answer_rows(pt, ans, ds, arm, "primary")} for ds in L.DATASETS for arm in L.ARMS}
out_md = []
P = out_md.append

# ── gold-loss funnel ─────────────────────────────────────────────────────────────────────────────────────────────
# Stage chain: ret50 (ranked candidates, the ceiling) -> top5 (raw chunks the gate sees) -> expansion (only if graph expansion ran)
# -> pruning -> context (both only on RAG/GRAPH routes; on LC the answerer saw the long context, so these records do not describe its input) -> answer.
CHAIN = [("ret50", "after_retrieval"), ("top5", "retrieved_top5"), ("expansion", "after_expansion"), ("pruning", "after_pruning"), ("context", "final_context")]
LABELS = [c[0] for c in CHAIN] + ["answer"]
rows = []                                                                    # one per (dataset, arm, task, kind)
for ds in L.DATASETS:
    for arm in FUNNEL_ARMS:
        for tid in ids[ds]:
            r = res[(ds, arm)][tid]
            g = gold[ds][tid]
            s = score[(ds, arm)][tid]
            rk = r.get("ranked") or {}
            for kind, gl, key in (("file", g["files"], "files"), ("function", g["functions"], "functions")):
                comp, per = {}, {}
                for lab, st in CHAIN:
                    items = (rk.get(st) or {}).get(key) or []
                    defined = True
                    if lab in ("pruning", "context"):
                        defined = r["route"] != "LC"                          # LC: the answerer saw the long context
                    elif lab == "expansion":
                        defined = bool((rk.get(st) or {}).get("files")) and r["route"] in ("GRAPH", "LC")   # expansion ran
                    comp[lab] = (all(x in set(items) for x in gl) and bool(gl)) if defined else None
                    per[lab] = "".join("1" if x in set(items) else "0" for x in gl) if defined else "n/a"
                acc = s["file_acc@5"] if kind == "file" else s["function_acc@10"]
                comp["answer"] = acc >= 1.0
                rows.append({"dataset": ds, "arm": arm, "task_id": tid, "route": r["route"], "kind": kind, "n_gold": len(gl), "failed": s["failed"],
                             **{f"complete_{k}": v for k, v in comp.items()}, "answer_acc": acc,
                             **{f"per_gold_{k}": v for k, v in per.items()}, "gold_paths": ";".join(gl)})
with open(HERE / "gold_loss_funnel.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0]))
    w.writeheader()
    w.writerows(rows)

P("# Gold-loss funnel and floor/tier analysis, Nov 3 jobs\n")
P("Generated by `docs/analysis/gate_diagnostics/build_funnel_floor.py`; read-only. Zero rule applied: a failed task scores 0 at the answer level. "
  "Per-task rows are in `gold_loss_funnel.csv` (one row per dataset, arm, task, file/function) and `floor_tiers.csv` (floor/tier tables are in the sections below).\n")
P("**Stages** (from `ranked.*` in each results row): *ret50* = `after_retrieval`, the 50 ranked candidates (the ceiling: gold absent here cannot be recovered by anything downstream); "
  "*top5* = `retrieved_top5`, the raw chunks the gate sees and the expansion seeds; *expansion* = `after_expansion` (only when graph expansion ran, i.e. GRAPH routes and Always-GRAPH); "
  "*pruning* = `after_pruning` and *context* = `final_context` (RAG and GRAPH routes only: on an LC route the answerer is given the long context and these lists do not describe its input, so they are treated as not applicable); "
  "*answer* = answer-level Acc@10 (functions) / Acc@5 (files) equal to 1. A task is 'complete' at a stage when every gold item is verbatim in that stage's list. "
  "Acc@k is binary per task in this data. Gold files are counted per task as a set (a task with 3 gold files needs all 3).\n")
P("## Gold funnel by arm and dataset\n")
P("Each cell is `complete / applicable tasks`. 'Lost' counts tasks complete at one stage and incomplete at the next applicable stage; 'gained' counts the reverse (a later stage can add gold the earlier one lacked, e.g. an answerer naming a gold file from the prompt, or expansion adding a neighbour).\n")
for kind in ("file", "function"):
    P(f"### Gold {kind}s\n")
    P("| Dataset | Arm | Tasks | ret50 | top5 | expansion | pruning | context | answer | Never in ret50 | Lost ret50→top5 | Lost top5→expansion | Lost →pruning | Lost →context | Lost →answer | Gained at some later stage |")
    P("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for ds in L.DATASETS:
        for arm in FUNNEL_ARMS:
            R = [r for r in rows if r["dataset"] == ds and r["arm"] == arm and r["kind"] == kind]
            cells = []
            for lab in LABELS:
                ap = [r for r in R if r[f"complete_{lab}"] is not None]
                cells.append(f"{sum(1 for r in ap if r[f'complete_{lab}'])}/{len(ap)}")
            lost = Counter()
            gained = 0
            for r in R:
                seq = [(lab, r[f"complete_{lab}"]) for lab in LABELS if r[f"complete_{lab}"] is not None]
                for (l0, c0), (l1, c1) in zip(seq, seq[1:]):
                    if c0 and not c1:
                        lost[l1] += 1
                    if c1 and not c0:
                        gained += 1
                        break
            never = sum(1 for r in R if r["complete_ret50"] is False and not r["per_gold_ret50"].count("1"))
            P(f"| {L.DS_LABEL[ds]} | {L.LABEL[arm]} | {len(R)} | " + " | ".join(cells) + f" | {never} | {lost['top5']} | {lost['expansion']} | {lost['pruning']} | {lost['context']} | {lost['answer']} | {gained} |")
    P("")
P("'Never in ret50' = no gold item at all among the 50 candidates (partial presence is not counted). 'Lost' columns are conditional on being complete at the previous applicable stage, "
  "so for an LC-routed task the only possible loss is →answer. Arms differ in what the stage lists record, so compare columns within an arm, not across arms, for the pruning and context stages.\n")

P("### Tasks losing gold at each stage, by dataset (gold files / gold functions)\n")
P("Same counts pooled over the four arms is not meaningful (the arms differ in route); the four arms are shown in the tables above. For a route-free view, the ret50 ceiling is shared by all arms:\n")
P("| Dataset | Tasks | Gold files complete in ret50 | Gold functions complete in ret50 | Files: none of the gold in ret50 | Functions: none of the gold in ret50 |")
P("|---|---|---|---|---|---|")
for ds in L.DATASETS:
    R = [r for r in rows if r["dataset"] == ds and r["arm"] == "GAPA"]
    F = [r for r in R if r["kind"] == "file"]
    Fn = [r for r in R if r["kind"] == "function"]
    P(f"| {L.DS_LABEL[ds]} | {len(F)} | {sum(1 for r in F if r['complete_ret50'])} | {sum(1 for r in Fn if r['complete_ret50'])} | "
      f"{sum(1 for r in F if not r['per_gold_ret50'].count('1'))} | {sum(1 for r in Fn if not r['per_gold_ret50'].count('1'))} |")
P("")

# gold paths not in the base commit
P("## Gold paths that are not in the base commit\n")
P("Files: `checkout_summary.json` for each dataset records `gold_files_missing_in_checkout`; answer scoring records `n_paths_not_in_checkout` for paths the model *wrote* that do not exist. "
  "Functions: `labels.jsonl` lists `added_functions` (functions the fix adds; they do not exist at the base commit and are excluded from the gold `functions` list used for scoring).\n")
P("| Dataset | Tasks | Tasks with a gold file missing in checkout | Gold files | Tasks with `added_functions` | Added functions in those tasks | Gold functions scored |")
P("|---|---|---|---|---|---|---|")
for ds in L.DATASETS:
    summ = json.load(open(DATA / ds / "checkout_summary.json")) if (DATA / ds / "checkout_summary.json").exists() else {}
    miss = summ.get("gold_files_missing_in_checkout")
    G = [gold[ds][t] for t in ids[ds]]
    P(f"| {L.DS_LABEL[ds]} | {len(G)} | {('not reported' if miss is None else len(miss) if isinstance(miss, list) else miss)} (whole dataset) | "
      f"{sum(len(g['files']) for g in G)} | {sum(1 for g in G if g['added_functions'])} | {sum(len(g['added_functions']) for g in G)} | {sum(len(g['functions']) for g in G)} |")
P("")
bad = defaultdict(lambda: [0, 0])                                           # (dataset, arm) -> [paths written, paths not in checkout]
for ds in L.DATASETS:
    for arm in FUNNEL_ARMS:
        for a in ans[(ds, arm)].values():
            bad[(ds, arm)][0] += int(a["n_paths"])
            bad[(ds, arm)][1] += int(a["n_paths_not_in_checkout"])
P("Paths the *answer* named that do not exist in the checkout (any reading of the zero rule: these are raw counts from `answer_scores.csv`):\n")
P("| Dataset | Arm | Paths written | Not in checkout |")
P("|---|---|---|---|")
for ds in L.DATASETS:
    for arm in FUNNEL_ARMS:
        P(f"| {L.DS_LABEL[ds]} | {L.LABEL[arm]} | {bad[(ds, arm)][0]} | {bad[(ds, arm)][1]} |")
P("")

# ── floor and tier differences ───────────────────────────────────────────────────────────────────────────────────
P("## Floor effect\n")
P("Fixed tiers: Always-RAG, Always-GRAPH, Always-LC. 'Floor' = all three score 0 on the task (zero rule applied).\n")
P("| Dataset | Tasks | Function Acc@10: all tiers 0 | Function Acc@10: tiers differ | Function Acc@10: all tiers equal and >0 | File Acc@5: all tiers 0 | File Acc@5: tiers differ | File Acc@5: all tiers equal and >0 |")
P("|---|---|---|---|---|---|---|---|")
TIERS = [("RAG", "ALWAYS_RAG"), ("GRAPH", "ALWAYS_GRAPH"), ("LC", "ALWAYS_LC")]
floor_rows = []
diff = {}
for ds in L.DATASETS:
    cells = []
    for metric in ("function_acc@10", "file_acc@5"):
        zero = differ = same_pos = 0
        for tid in ids[ds]:
            v = {rt: score[(ds, arm)][tid][metric] for rt, arm in TIERS}
            if len(set(v.values())) > 1:
                differ += 1
                diff.setdefault((ds, metric), []).append((tid, v))
            elif max(v.values()) == 0:
                zero += 1
            else:
                same_pos += 1
        cells += [zero, differ, same_pos]
        floor_rows.append({"dataset": ds, "metric": metric, "tasks": len(ids[ds]), "all_zero": zero, "differ": differ, "all_equal_positive": same_pos})
    P(f"| {L.DS_LABEL[ds]} | {len(ids[ds])} | " + " | ".join(map(str, cells)) + " |")
P("")

P("## Tasks where the tiers differ\n")
for metric in ("function_acc@10", "file_acc@5"):
    P(f"### {metric}\n")
    P("Winner = tier(s) with the highest score; the cheapest winner (RAG < GRAPH < LC) is the ideal route.\n")
    P("| Dataset | Task | RAG | GRAPH | LC | Winner(s) | Ideal route |")
    P("|---|---|---|---|---|---|---|")
    for ds in L.DATASETS:
        for tid, v in sorted(diff.get((ds, metric), [])):
            best = max(v.values())
            win = [rt for rt in v if v[rt] == best]
            P(f"| {L.DS_LABEL[ds]} | {tid} | {v['RAG']:.0f} | {v['GRAPH']:.0f} | {v['LC']:.0f} | {'/'.join(win)} | {min(win, key=RANK.get)} |")
    P("")
    wins = Counter()
    for (ds, m), lst in diff.items():
        if m != metric:
            continue
        for tid, v in lst:
            best = max(v.values())
            for rt in v:
                if v[rt] == best:
                    wins[(ds, rt)] += 1
    P("Winning-tier counts among differing tasks (ties count for each tied tier): " +
      "; ".join(f"{L.DS_LABEL[ds]} {rt} {wins[(ds, rt)]}" for ds in L.DATASETS for rt in RANK) + ".\n")

P("## Over- and under-escalation against the ideal route\n")
P("Ideal route per task = cheapest tier among those with the best score (as above), on the stated metric; when all three tiers tie, "
  "the ideal is RAG (nothing was gained by paying for more). Over-escalation = the arm's final route is more expensive than ideal; under-escalation = cheaper. "
  "'All 83' counts every task; 'Differing only' restricts to tasks where the tiers differ (where the route can matter).\n")
P("| Metric | Dataset | Arm | Scope | Tasks | Matches ideal | Over-escalated | Under-escalated | Failed-task routes (no route) |")
P("|---|---|---|---|---|---|---|---|---|")
for metric in ("function_acc@10", "file_acc@5"):
    for ds in L.DATASETS:
        ideal = {}
        for tid in ids[ds]:
            v = {rt: score[(ds, arm)][tid][metric] for rt, arm in TIERS}
            best = max(v.values())
            ideal[tid] = min((rt for rt in v if v[rt] == best), key=RANK.get)
        dset = {t for t, _ in diff.get((ds, metric), [])}
        for arm in GATED:
            for scope, S in (("All", set(ids[ds])), ("Differing only", dset)):
                m = o = u = nr = 0
                for tid in S:
                    rt = score[(ds, arm)][tid]["route"]
                    if rt not in RANK:
                        nr += 1
                        continue
                    if RANK[rt] == RANK[ideal[tid]]:
                        m += 1
                    elif RANK[rt] > RANK[ideal[tid]]:
                        o += 1
                    else:
                        u += 1
                P(f"| {metric} | {L.DS_LABEL[ds]} | {L.LABEL[arm]} | {scope} | {len(S)} | {m} | {o} | {u} | {nr} |")
                floor_rows.append({"dataset": ds, "metric": metric, "arm": arm, "scope": scope, "tasks": len(S), "match": m, "over": o, "under": u, "no_route": nr})
P("")
with open(HERE / "floor_tiers.csv", "w", newline="", encoding="utf-8") as f:
    keys = sorted({k for r in floor_rows for k in r})
    w = csv.DictWriter(f, fieldnames=keys)
    w.writeheader()
    w.writerows(floor_rows)
(HERE / "gold_loss_funnel.md").write_text("\n".join(out_md) + "\n", encoding="utf-8")
print("wrote gold_loss_funnel.md/.csv and floor_tiers.csv")
