def _windowed_code() -> str:
    # Only line 9 matches the query, so the window (radius=3) starts at snippet line 6.
    lines = [f"value_{i} = {i}" for i in range(8)] + ["target = compute()", "value_9 = 9"]
    return "\n".join(lines)


