def _make_items(n: int, code_len: int = 100) -> list[dict]:
    """Create n dummy retrieval items."""
    items = []
    for i in range(n):
        items.append({
            "code": f"def func_{i}():\n    " + "x = 1\n    " * (code_len // 10),
            "final_score": round(0.9 - i * 0.05, 2),
            "metadata": {"function": f"func_{i}", "file": f"mod_{i}.py"},
        })
    return items


