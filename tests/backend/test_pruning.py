# ── score_candidate ───────────────────────────────────────────


def test_score_candidate_returns_float():
    item = {
        "code": "def hello(): pass",
        "final_score": 0.8,
        "metadata": {"function": "hello", "file": "greet.py"},
    }
    s = score_candidate("hello function", item)
    assert isinstance(s, float)
    assert 0.0 <= s <= 1.0


def test_score_candidate_higher_for_relevant():
    relevant = {
        "code": "def get_users():\n    return db.query(User)",
        "final_score": 0.9,
        "metadata": {"function": "get_users", "file": "users.py"},
    }
    irrelevant = {
        "code": "# auto-generated\nx = 1",
        "final_score": 0.1,
        "metadata": {"function": "setup", "file": "test_config.py"},
    }
    assert score_candidate("get users", relevant) > score_candidate("get users", irrelevant)


