"""Write or verify the pinned environment (requirements.lock.txt).

  python -m harness.envlock --write     # from the CURRENT venv (Ubuntu build machine)
  python -m harness.envlock --verify    # compare the CURRENT venv with the lock (any OS)

The lock holds the dependency closure of the packages the pipeline and harness import.
Linux-only wheels (nvidia-*, triton) carry an environment marker so the same file installs on
Windows. torch is the one real platform exception: see the header of the lock file.
"""
from __future__ import annotations

import argparse
import re
import sys
from importlib.metadata import PackageNotFoundError, distribution, distributions
from pathlib import Path

from packaging.requirements import Requirement

from .envinfo import LOCK_PATH

ROOTS = ["chromadb", "sentence-transformers", "rank-bm25", "requests", "fastapi", "uvicorn",
         "pydantic", "numpy", "pytest", "typing_extensions", "torch", "transformers", "packaging"]
LINUX_ONLY_PREFIX = ("nvidia-", "triton", "cuda-")
# Dependencies that only Windows needs; not installed here, so the version cannot be read.
WINDOWS_ONLY = {"colorama": "0.4.6"}

HEADER = """\
# Pinned environment for the evaluation harness. Python 3.12 only.
# Create a NEW venv and install with:  python -m harness.install_env --venv <new-dir>
# Generated by: python -m harness.envlock --write   (do not edit by hand)
#
# Platform exceptions:
#  * torch: the pin is the version, not the CUDA build. On Windows, plain PyPI gives a CPU-only
#    wheel; for CUDA use --torch-index-url (see install_env). Query embedding runs on CPU either way.
#  * nvidia-*, cuda-* and triton are Linux-only wheels (marker below); Windows torch wheels bundle CUDA.
#  * colorama is needed on Windows only; its version was not resolved on the Ubuntu machine.
#  * Not pip-installable here: Ollama and the graphify CLI (version recorded in log headers).
"""


def norm(n: str) -> str:
    return re.sub(r"[-_.]+", "-", n).lower()


def closure() -> dict[str, str]:
    seen: dict[str, str] = {}

    def walk(n: str) -> None:
        n = norm(n)
        if n in seen:
            return
        try:
            d = distribution(n)
        except PackageNotFoundError:
            return
        seen[n] = d.version
        for r in d.requires or []:
            q = Requirement(r)
            if q.marker is not None and not q.marker.evaluate({"extra": ""}):
                continue
            walk(q.name)

    for r in ROOTS:
        walk(r)
    for d in distributions():          # CUDA runtime wheels torch pulls in under other markers
        n = norm(d.metadata["Name"])
        if n.startswith(LINUX_ONLY_PREFIX):
            seen[n] = d.version
    return seen


def render(pins: dict[str, str]) -> str:
    lines = [HEADER]
    for n, v in sorted(pins.items()):
        mark = '; sys_platform == "linux"' if n.startswith(LINUX_ONLY_PREFIX) else ""
        lines.append(f"{n}=={v}{mark}")
    for n, v in WINDOWS_ONLY.items():
        lines.append(f'{n}=={v}; sys_platform == "win32"')
    return "\n".join(lines) + "\n"


def parse_lock(path: Path = LOCK_PATH) -> dict[str, tuple[str, str]]:
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        q = Requirement(line)
        ver = next(iter(q.specifier)).version
        out[norm(q.name)] = (ver, str(q.marker) if q.marker else "")
    return out


def verify(path: Path = LOCK_PATH) -> int:
    bad = 0
    for n, (ver, marker) in parse_lock(path).items():
        if marker and not Requirement(f"x; {marker}").marker.evaluate():
            continue
        try:
            have = distribution(n).version
        except PackageNotFoundError:
            print(f"[FAIL] {n}=={ver} not installed")
            bad += 1
            continue
        if have != ver:
            print(f"[FAIL] {n}: installed {have}, locked {ver}")
            bad += 1
    print("[PASS] environment matches lock" if not bad else f"{bad} mismatches")
    return 1 if bad else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--verify", action="store_true")
    a = ap.parse_args()
    if sys.version_info[:2] != (3, 12):
        print(f"[FAIL] Python 3.12 required, found {sys.version.split()[0]}")
        return 2
    if a.verify:
        return verify()
    pins = closure()
    LOCK_PATH.write_text(render(pins), encoding="utf-8", newline="\n")
    print(f"wrote {LOCK_PATH} ({len(pins)} pins)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
